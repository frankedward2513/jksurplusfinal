create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id text,
  action text not null check (action in ('INSERT', 'UPDATE', 'DELETE')),
  actor_id uuid,
  actor_name text not null,
  actor_email text,
  occurred_at timestamptz not null default now()
);

alter table public.audit_logs
  add column if not exists actor_role text check (actor_role in ('admin', 'staff'));

update public.audit_logs
set actor_role = case lower(actor_email)
  when 'exinadmin@gmail.com' then 'admin'
  when 'exinstaff@gmail.com' then 'staff'
end
where actor_role is null
  and lower(actor_email) in ('exinadmin@gmail.com', 'exinstaff@gmail.com');

alter table public.audit_logs enable row level security;

drop policy if exists "Admins can read activity logs" on public.audit_logs;
create policy "Admins can read activity logs"
  on public.audit_logs
  for select
  to authenticated
  using (
    lower(coalesce(auth.jwt() ->> 'email', '')) = 'exinadmin@gmail.com'
    and auth.jwt() -> 'app_metadata' ->> 'provider' = 'email'
    and auth.jwt() -> 'app_metadata' ->> 'exins_role' = 'admin'
  );

revoke all on public.audit_logs from anon, authenticated;
grant select on public.audit_logs to authenticated;

create or replace function public.capture_audit_log()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  old_row jsonb;
  new_row jsonb;
  row_id text;
  user_metadata jsonb;
  user_email text;
  user_role text;
begin
  if tg_op <> 'INSERT' then
    old_row := to_jsonb(old);
  end if;
  if tg_op <> 'DELETE' then
    new_row := to_jsonb(new);
  end if;

  if tg_table_name = 'transactions'
    and coalesce(new_row ->> 'category', '') <> 'POS Sales'
    and coalesce(old_row ->> 'category', '') <> 'POS Sales'
  then
    if tg_op = 'DELETE' then
      return old;
    end if;
    return new;
  end if;

  row_id := coalesce(new_row ->> 'id', old_row ->> 'id');
  user_metadata := coalesce(auth.jwt() -> 'user_metadata', '{}'::jsonb);
  user_email := auth.jwt() ->> 'email';
  user_role := auth.jwt() -> 'app_metadata' ->> 'exins_role';

  insert into public.audit_logs (
    table_name,
    record_id,
    action,
    actor_id,
    actor_role,
    actor_name,
    actor_email
  )
  values (
    tg_table_name,
    row_id,
    tg_op,
    auth.uid(),
    case when user_role in ('admin', 'staff') then user_role else null end,
    coalesce(
      nullif(user_metadata ->> 'full_name', ''),
      nullif(user_metadata ->> 'name', ''),
      user_email,
      'Unknown user'
    ),
    user_email
  );

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

revoke all on function public.capture_audit_log() from public, anon, authenticated;

do $$
declare
  target_table record;
begin
  for target_table in
    select tablename
    from pg_tables
    where schemaname = 'public'
      and tablename <> 'audit_logs'
  loop
    execute format(
      'drop trigger if exists capture_audit_log on public.%I',
      target_table.tablename
    );
  end loop;

  for target_table in
    select unnest(array[
      'bales',
      'categories',
      'products',
      'suppliers',
      'item_logs',
      'orders',
      'transactions'
    ]) as tablename
  loop
    if to_regclass(format('public.%I', target_table.tablename)) is not null then
      execute format(
        'create trigger capture_audit_log after insert or update or delete on public.%I '
        'for each row execute function public.capture_audit_log()',
        target_table.tablename
      );
    end if;
  end loop;
end;
$$;

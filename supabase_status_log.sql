create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  table_name text not null,
  record_id text,
  action text not null,
  actor_id uuid,
  actor_name text not null,
  actor_email text,
  actor_role text not null check (actor_role in ('admin', 'staff')),
  occurred_at timestamptz not null default now()
);

alter table public.audit_logs
  add column if not exists actor_role text;

alter table public.audit_logs
  drop constraint if exists audit_logs_action_check;

alter table public.audit_logs
  add constraint audit_logs_action_check
  check (action in ('INSERT', 'UPDATE', 'DELETE', 'SALE', 'LOST'));

alter table public.audit_logs
  drop constraint if exists audit_logs_actor_role_check;

alter table public.audit_logs
  add constraint audit_logs_actor_role_check
  check (actor_role in ('admin', 'staff'));

alter table public.audit_logs enable row level security;

drop policy if exists "Admins can read activity logs" on public.audit_logs;
drop policy if exists "Admins can read status logs" on public.audit_logs;
create policy "Admins can read status logs"
  on public.audit_logs
  for select
  to authenticated
  using (
    lower(coalesce(auth.jwt() ->> 'email', '')) = 'exinadmin@gmail.com'
    and auth.jwt() -> 'app_metadata' ->> 'provider' = 'email'
    and auth.jwt() -> 'app_metadata' ->> 'exins_role' = 'admin'
  );

revoke all on public.audit_logs from anon, authenticated;
grant select on public.audit_logs to authenticated;

create or replace function public.capture_status_log()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  old_row jsonb;
  new_row jsonb;
  row_id text;
  user_metadata jsonb;
  user_email text;
  user_role text;
  log_action text;
begin
  if tg_op <> 'INSERT' then
    old_row := to_jsonb(old);
  end if;
  if tg_op <> 'DELETE' then
    new_row := to_jsonb(new);
  end if;

  user_email := auth.jwt() ->> 'email';
  user_role := lower(coalesce(auth.jwt() -> 'app_metadata' ->> 'exins_role', ''));
  if user_role not in ('admin', 'staff') then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  if tg_table_name = 'orders' then
    if tg_op <> 'INSERT' or left(coalesce(new_row ->> 'id', ''), 4) <> 'pos_' then
      return new;
    end if;
    row_id := coalesce(new_row ->> 'order_number', new_row ->> 'id');
    log_action := 'SALE';
  elsif tg_table_name = 'item_logs' then
    if tg_op <> 'INSERT' or lower(coalesce(new_row ->> 'type', '')) <> 'lost' then
      if tg_op = 'DELETE' then return old; end if;
      return new;
    end if;
    row_id := new_row ->> 'id';
    log_action := 'LOST';
  elsif tg_table_name = 'transactions' then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  elsif tg_table_name = 'products'
    and tg_op = 'UPDATE'
    and (new_row - 'available_quantity' - 'availableQuantity' - 'updated_at' - 'updatedAt')
      = (old_row - 'available_quantity' - 'availableQuantity' - 'updated_at' - 'updatedAt')
  then
    return new;
  elsif tg_table_name = 'bales'
    and tg_op = 'UPDATE'
    and (new_row - 'total_sales_made') = (old_row - 'total_sales_made')
  then
    return new;
  else
    row_id := coalesce(new_row ->> 'id', old_row ->> 'id');
    log_action := tg_op;
  end if;

  user_metadata := coalesce(auth.jwt() -> 'user_metadata', '{}'::jsonb);

  insert into public.audit_logs (
    table_name,
    record_id,
    action,
    actor_id,
    actor_name,
    actor_email,
    actor_role
  )
  values (
    case when log_action = 'SALE' then 'POS' when log_action = 'LOST' then 'Log Lost Item' else tg_table_name end,
    row_id,
    log_action,
    auth.uid(),
    coalesce(
      nullif(user_metadata ->> 'full_name', ''),
      nullif(user_metadata ->> 'name', ''),
      user_email,
      'Unknown user'
    ),
    user_email,
    user_role
  );

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function public.capture_status_log() from public, anon, authenticated;

do $$
declare
  old_trigger record;
  target_table text;
begin
  for old_trigger in
    select trigger_namespace.nspname as schema_name, target_table.relname as table_name, trigger_row.tgname as trigger_name
    from pg_trigger as trigger_row
    join pg_class as target_table on target_table.oid = trigger_row.tgrelid
    join pg_namespace as trigger_namespace on trigger_namespace.oid = target_table.relnamespace
    join pg_proc as trigger_function on trigger_function.oid = trigger_row.tgfoid
    join pg_namespace as function_namespace on function_namespace.oid = trigger_function.pronamespace
    where function_namespace.nspname = 'public'
      and trigger_function.proname = 'capture_audit_log'
      and not trigger_row.tgisinternal
  loop
    execute format(
      'drop trigger if exists %I on %I.%I',
      old_trigger.trigger_name,
      old_trigger.schema_name,
      old_trigger.table_name
    );
  end loop;

  drop function if exists public.capture_audit_log();

  foreach target_table in array array['bales', 'categories', 'products', 'suppliers', 'item_logs', 'orders']
  loop
    if to_regclass(format('public.%I', target_table)) is not null then
      execute format('drop trigger if exists capture_status_log on public.%I', target_table);
      execute format(
        'create trigger capture_status_log after insert or update or delete on public.%I '
        'for each row execute function public.capture_status_log()',
        target_table
      );
    end if;
  end loop;
end;
$$;

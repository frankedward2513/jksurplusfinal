create table if not exists public.exbin_archive (
  archive_id bigint generated by default as identity primary key,
  trash_id text not null unique,
  table_name text not null,
  record_id text not null,
  record_data jsonb not null,
  deleted_at timestamptz not null,
  expires_at timestamptz not null,
  archived_at timestamptz not null default now()
);

alter table public.exbin_archive enable row level security;

drop policy if exists "Admins can read exBIN archive" on public.exbin_archive;
create policy "Admins can read exBIN archive"
  on public.exbin_archive
  for select
  to authenticated
  using (
    lower(coalesce(auth.jwt() ->> 'email', '')) = 'exinadmin@gmail.com'
    and auth.jwt() -> 'app_metadata' ->> 'provider' = 'email'
    and auth.jwt() -> 'app_metadata' ->> 'exins_role' = 'admin'
  );

revoke all on public.exbin_archive from anon, authenticated;
grant select on public.exbin_archive to authenticated;

create or replace function public.archive_expired_exbin_trash()
returns integer
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  archived_count integer;
begin
  perform pg_advisory_xact_lock(hashtext('archive_expired_exbin_trash'));

  insert into public.exbin_archive (
    trash_id,
    table_name,
    record_id,
    record_data,
    deleted_at,
    expires_at
  )
  select
    id::text,
    table_name,
    record_id::text,
    record_data::jsonb,
    deleted_at,
    expires_at
  from public.exbin_trash
  where expires_at <= now()
  on conflict (trash_id) do nothing;

  get diagnostics archived_count = row_count;

  delete from public.exbin_trash
  where expires_at <= now();

  return archived_count;
end;
$$;

revoke all on function public.archive_expired_exbin_trash() from public, anon, authenticated;

create extension if not exists pg_cron with schema pg_catalog;

do $$
declare
  existing_job record;
begin
  for existing_job in
    select jobid
    from cron.job
    where jobname = 'archive-expired-exbin-trash'
  loop
    perform cron.unschedule(existing_job.jobid);
  end loop;

  perform cron.schedule(
    'archive-expired-exbin-trash',
    '0 * * * *',
    'select public.archive_expired_exbin_trash();'
  );
end;
$$;
